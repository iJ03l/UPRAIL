package escrow

import (
	"fmt"
	"regexp"
	"strings"
)

// ValidationError marks a request that must not be retried (HTTP 400).
type ValidationError struct{ Msg string }

func (e *ValidationError) Error() string { return e.Msg }

// ConflictError marks an idempotency conflict (HTTP 409).
type ConflictError struct{ Msg string }

func (e *ConflictError) Error() string { return e.Msg }

func invalid(format string, args ...any) error {
	return &ValidationError{Msg: fmt.Sprintf(format, args...)}
}

func conflict(format string, args ...any) error {
	return &ConflictError{Msg: fmt.Sprintf(format, args...)}
}

var (
	// NEAR account IDs: dot-separated lowercase segments, 2–64 chars total overall bound.
	nearAccountIDRe = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9._-]{0,62}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9._-]{0,62}[a-z0-9])?)*$`)
	// Amounts: plain decimal only — no sign, no exponent, at most 18 fractional digits.
	amountRe = regexp.MustCompile(`^[0-9]{1,40}(?:\.[0-9]{1,18})?$`)
	// Assets: short opaque identifiers (e.g. "near", "wrap.near", "nep141:usdc.near").
	assetRe = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9:._-]{0,63}$`)
	// Payment IDs generated by the worker (ULID / UUID / `<ulid>_fee`).
	paymentIDRe = regexp.MustCompile(`^[A-Za-z0-9_-]{8,64}$`)
	// EVM address: 0x followed by 40 hex chars
	evmAddressRe = regexp.MustCompile(`^0x[a-fA-F0-9]{40}$`)
	// Solana address: 32-44 base58 chars
	solanaAddressRe = regexp.MustCompile(`^[1-9A-HJ-NP-Za-km-z]{32,44}$`)
)

// IsCrossChainAddress checks if the address is an EVM or Solana destination.
func IsCrossChainAddress(addr string) bool {
	clean := strings.TrimSpace(addr)
	if evmAddressRe.MatchString(clean) {
		return true
	}
	if !strings.Contains(clean, ".") && solanaAddressRe.MatchString(clean) && len(clean) != 64 {
		return true
	}
	return false
}

// ValidateRecipient accepts valid NEAR accounts as well as EVM and Solana addresses.
func ValidateRecipient(field, value string) error {
	clean := strings.TrimSpace(value)
	if clean == "" {
		return invalid("%s is required", field)
	}
	if IsCrossChainAddress(clean) {
		return nil
	}
	return ValidateNearAccountID(field, clean)
}

// ValidateNearAccountID rejects anything that is not a well-formed NEAR account ID.
func ValidateNearAccountID(field, value string) error {
	clean := strings.TrimSpace(value)
	if clean == "" {
		return invalid("%s is required", field)
	}
	if len(clean) < 2 || len(clean) > 64 || !nearAccountIDRe.MatchString(clean) {
		return invalid("%s is not a valid NEAR account ID", field)
	}
	for _, part := range strings.Split(clean, ".") {
		if len(part) == 0 || len(part) > 64 {
			return invalid("%s is not a valid NEAR account ID", field)
		}
	}
	return nil
}

// ValidateAmount rejects zero, negative, exponential or otherwise malformed
// quantities. Amounts are compared as exact decimal strings.
func ValidateAmount(field, value string) error {
	clean := strings.TrimSpace(value)
	if clean == "" {
		return invalid("%s is required", field)
	}
	if !amountRe.MatchString(clean) {
		return invalid("%s must be a plain positive decimal number", field)
	}
	if isAllZero(clean) {
		return invalid("%s must be greater than zero", field)
	}
	return nil
}

// ValidateAsset rejects empty or oversized asset identifiers.
func ValidateAsset(field, value string) error {
	clean := strings.TrimSpace(value)
	if clean == "" {
		return invalid("%s is required", field)
	}
	if !assetRe.MatchString(clean) {
		return invalid("%s contains unsupported characters", field)
	}
	return nil
}

// ValidatePaymentID requires a worker-generated payment identifier so every
// settlement is bound to a specific payment record.
func ValidatePaymentID(value string) error {
	clean := strings.TrimSpace(value)
	if clean == "" {
		return invalid("paymentId is required")
	}
	if !paymentIDRe.MatchString(clean) {
		return invalid("paymentId is malformed")
	}
	return nil
}

// ValidateEscrowBinding ensures a request may only spend from the configured
// escrow account. The field is required: an omitted escrow account would let
// the signer drift if multiple accounts were ever configured.
func (s *TransferService) ValidateEscrowBinding(requested string) error {
	if s.signer == nil {
		return invalid("escrow signer is not configured")
	}
	clean := strings.TrimSpace(requested)
	if clean == "" {
		return invalid("escrowAccountId is required and must match the configured escrow account")
	}
	if !strings.EqualFold(clean, s.signer.AccountID()) {
		return invalid("escrow account mismatch")
	}
	return nil
}

